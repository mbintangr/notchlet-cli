import { createHash, randomUUID } from 'node:crypto';
import { lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

export type McpClient = 'opencode' | 'claude';
/** `bridge` and `local` run stdio; `remote` points the client at `<origin>/mcp` directly. */
export type McpTransport = 'bridge' | 'remote' | 'local';
/** OpenCode reads legacy flat `mcp.<name>` entries and the V2 `mcp.servers.<name>` shape. */
export type OpenCodeConfigShape = 'legacy' | 'v2';
export type McpConfigAction = 'create' | 'update' | 'unchanged' | 'conflict';

export type McpConfigPreview = {
  client: McpClient;
  path: string;
  relativePath: string;
  exists: boolean;
  action: McpConfigAction;
  reason?: string;
  /** Canonical hash of the Notchlet entry when the merge is actionable. */
  entryHash?: string;
};

const OPENCODE_CANDIDATES = ['opencode.json', 'opencode.jsonc', path.join('.opencode', 'opencode.json'), path.join('.opencode', 'opencode.jsonc'), path.join('.opencode', 'config.json')];
const CLAUDE_RELATIVE = '.mcp.json';

export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') return `{${Object.entries(value as Record<string, unknown>).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([key, entry]) => `${JSON.stringify(key)}:${canonicalJson(entry)}`).join(',')}}`;
  return JSON.stringify(value);
}

/**
 * OpenCode treats `enabled: true` and `disabled: false` as the default, so they
 * are ignored when comparing entries. That keeps entries generated by older CLI
 * versions (which wrote `enabled: true`) equivalent to the current default.
 */
function normalizeServerEntry(value: unknown): unknown {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return value;
  const normalized: Record<string, unknown> = { ...(value as Record<string, unknown>) };
  if (normalized.enabled === true) delete normalized.enabled;
  if (normalized.disabled === false) delete normalized.disabled;
  return normalized;
}

export function hashMcpEntry(value: unknown): string {
  return createHash('sha256').update(canonicalJson(normalizeServerEntry(value))).digest('hex');
}

/** The non-secret invocation written into client configuration. */
export function mcpServeInvocation(origin: string): string[] {
  return ['notchlet', 'mcp', 'serve', '--server', origin];
}

export function mcpLocalInvocation(): string[] {
  return ['notchlet', 'mcp', 'serve', '--local'];
}

export const DEFAULT_MCP_TOKEN_ENV = 'NOTCHLET_MCP_TOKEN';

/**
 * No `enabled` field: the V2 `mcp.servers` schema uses `disabled` (default
 * false) and rejects unknown keys, while legacy flat entries and OpenCode
 * 1.19.5 both default an omitted field to enabled. Omitting keeps one entry
 * valid in both shapes.
 */
export function openCodeServerEntry(origin: string) {
  return { type: 'local', command: mcpServeInvocation(origin) };
}

export function openCodeLocalServerEntry() {
  return { type: 'local', command: mcpLocalInvocation() };
}

/** Remote entry matching OpenCode's documented `type: "remote"` shape. */
export function openCodeRemoteServerEntry(origin: string, tokenEnv = DEFAULT_MCP_TOKEN_ENV) {
  return {
    type: 'remote',
    url: `${origin}/mcp`,
    headers: { Authorization: `Bearer {env:${tokenEnv}}` },
  };
}

export function claudeServerEntry(origin: string) {
  return { type: 'stdio', command: 'notchlet', args: mcpServeInvocation(origin).slice(1), env: {} };
}

export function claudeLocalServerEntry() {
  return { type: 'stdio', command: 'notchlet', args: mcpLocalInvocation().slice(1), env: {} };
}

/** Claude Code's streamable HTTP transport uses `type: "http"` with headers. */
export function claudeRemoteServerEntry(origin: string, tokenEnv = DEFAULT_MCP_TOKEN_ENV) {
  return {
    type: 'http',
    url: `${origin}/mcp`,
    headers: { Authorization: `Bearer \${${tokenEnv}}` },
  };
}

export function desiredMcpEntry(client: McpClient, origin: string, options: { transport?: McpTransport; tokenEnv?: string } = {}) {
  const transport = options.transport ?? 'bridge';
  if (client === 'opencode') {
    if (transport === 'remote') return openCodeRemoteServerEntry(origin, options.tokenEnv);
    if (transport === 'local') return openCodeLocalServerEntry();
    return openCodeServerEntry(origin);
  }
  if (transport === 'remote') return claudeRemoteServerEntry(origin, options.tokenEnv);
  if (transport === 'local') return claudeLocalServerEntry();
  return claudeServerEntry(origin);
}

async function lstatOrNull(file: string) {
  try { return await lstat(file); } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null; throw error; }
}

async function assertSafeParents(root: string, relative: string) {
  let current = root;
  for (const segment of path.dirname(relative).split(path.sep).filter(Boolean)) {
    current = path.join(current, segment);
    const stat = await lstatOrNull(current);
    if (stat?.isSymbolicLink() || (stat && !stat.isDirectory())) return `Configuration directory traverses a non-directory or symlink: ${relative}`;
  }
  const target = await lstatOrNull(path.join(root, relative));
  if (target?.isSymbolicLink()) return `Configuration file is a symbolic link: ${relative}`;
  if (target && !target.isFile()) return `Configuration target is not a regular file: ${relative}`;
  return undefined;
}

/** Strip comments and trailing commas from JSONC without touching string contents. */
export function parseJsonc(text: string): unknown {
  let out = '';
  let inString = false, escaped = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i], next = text[i + 1];
    if (inString) {
      out += char;
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') { inString = true; out += char; continue; }
    if (char === '/' && next === '/') { while (i < text.length && text[i] !== '\n') i++; if (i < text.length) out += '\n'; continue; }
    if (char === '/' && next === '*') { i += 2; while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i++; i++; continue; }
    out += char;
  }
  return JSON.parse(out.replace(/,\s*([}\]])/g, '$1'));
}

async function projectConfigPath(root: string, client: McpClient): Promise<{ file: string; relative: string }> {
  if (client === 'claude') return { file: path.join(root, CLAUDE_RELATIVE), relative: CLAUDE_RELATIVE };
  for (const candidate of OPENCODE_CANDIDATES) {
    if (await lstatOrNull(path.join(root, candidate))) return { file: path.join(root, candidate), relative: candidate };
  }
  return { file: path.join(root, 'opencode.json'), relative: 'opencode.json' };
}

type LoadedConfig = { exists: boolean; value?: Record<string, any>; text?: string };

async function loadConfig(root: string, client: McpClient): Promise<{ file: string; relative: string; loaded: LoadedConfig } & { problem?: string }> {
  const { file, relative } = await projectConfigPath(root, client);
  const problem = await assertSafeParents(root, relative);
  if (problem) return { file, relative, loaded: { exists: true }, problem };
  const stat = await lstatOrNull(file);
  if (!stat) return { file, relative, loaded: { exists: false } };
  const text = await readFile(file, 'utf8');
  try {
    const raw = file.endsWith('.jsonc') ? parseJsonc(text) : JSON.parse(text);
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return { file, relative, loaded: { exists: true, text }, problem: 'Configuration root must be a JSON object.' };
    return { file, relative, loaded: { exists: true, value: raw as Record<string, any>, text } };
  } catch {
    return { file, relative, loaded: { exists: true, text }, problem: 'Configuration file is not valid JSON; fix or remove it before configuring MCP.' };
  }
}

type ServerContainer = {
  servers: Record<string, any>;
  shape: OpenCodeConfigShape;
  /** A legacy flat `mcp.notchlet` that shadows `mcp.servers.notchlet` in OpenCode. */
  shadow?: any;
};

function container(value: Record<string, any>, client: McpClient): ServerContainer {
  if (client === 'claude') {
    if (value.mcpServers === undefined) value.mcpServers = {};
    if (!value.mcpServers || typeof value.mcpServers !== 'object' || Array.isArray(value.mcpServers)) throw new Error('Configuration key "mcpServers" must be an object.');
    return { servers: value.mcpServers, shape: 'legacy' };
  }
  if (value.mcp === undefined) value.mcp = {};
  if (!value.mcp || typeof value.mcp !== 'object' || Array.isArray(value.mcp)) throw new Error('Configuration key "mcp" must be an object.');
  const mcp = value.mcp as Record<string, any>;
  if (mcp.servers === undefined) return { servers: mcp, shape: 'legacy' };
  if (!mcp.servers || typeof mcp.servers !== 'object' || Array.isArray(mcp.servers)) throw new Error('Configuration key "mcp.servers" must be an object.');
  return { servers: mcp.servers, shape: 'v2', ...(mcp.notchlet !== undefined ? { shadow: mcp.notchlet } : {}) };
}

export type MergeOptions = { managedEntryHash?: string; apply?: boolean; transport?: McpTransport; tokenEnv?: string };

export async function mergeMcpProjectConfig(rootInput: string, client: McpClient, origin: string, options: MergeOptions = {}): Promise<McpConfigPreview> {
  const root = path.resolve(rootInput);
  const desired = desiredMcpEntry(client, origin, options);
  const entryHash = hashMcpEntry(desired);
  const { file, relative, loaded, problem } = await loadConfig(root, client);
  if (problem) return { client, path: file, relativePath: relative, exists: loaded.exists, action: 'conflict', reason: problem };

  const value = loaded.value ?? {};
  let servers: Record<string, any>;
  let shape: OpenCodeConfigShape;
  let shadow: any;
  try { ({ servers, shape, shadow } = container(value, client)); }
  catch (error) { return { client, path: file, relativePath: relative, exists: loaded.exists, action: 'conflict', reason: (error as Error).message }; }

  if (client === 'opencode' && shape === 'v2' && shadow !== undefined) {
    // OpenCode 1.19.5 resolves the legacy flat key first, so a flat entry would
    // silently override the V2 entry. Refuse to write a shadowed configuration.
    if (hashMcpEntry(shadow) !== entryHash) {
      return { client, path: file, relativePath: relative, exists: loaded.exists, action: 'conflict', entryHash, reason: 'A legacy flat "mcp.notchlet" entry overrides "mcp.servers.notchlet" in OpenCode; reconcile it before MCP setup.' };
    }
    return { client, path: file, relativePath: relative, exists: loaded.exists, action: 'unchanged', entryHash };
  }

  const existing = servers.notchlet;
  let action: McpConfigAction;
  if (existing === undefined) action = loaded.exists ? 'update' : 'create';
  else {
    const existingHash = hashMcpEntry(existing);
    if (existingHash === entryHash) action = 'unchanged';
    else if (options.managedEntryHash && options.managedEntryHash === existingHash) action = 'update';
    else return { client, path: file, relativePath: relative, exists: loaded.exists, action: 'conflict', entryHash, reason: 'An existing Notchlet MCP entry differs from the generated entry; it was preserved. Remove or reconcile it, then rerun setup.' };
  }

  if (options.apply && (action === 'create' || action === 'update')) {
    servers.notchlet = desired;
    await mkdir(path.dirname(file), { recursive: true });
    const temporary = `${file}.${randomUUID()}.tmp`;
    await writeFile(temporary, `${JSON.stringify(value, null, 2)}\n`, { flag: 'wx', mode: 0o600 });
    try { await rename(temporary, file); }
    catch (error) { await rm(temporary, { force: true }); throw error; }
  }
  return { client, path: file, relativePath: relative, exists: loaded.exists, action, entryHash };
}

export async function inspectMcpProjectConfig(rootInput: string, client: McpClient, origin: string, options: MergeOptions = {}): Promise<McpConfigPreview & { present: boolean }> {
  const root = path.resolve(rootInput);
  const preview = await mergeMcpProjectConfig(root, client, origin, options);
  if (preview.action === 'conflict' && (preview.reason?.includes('differs from the generated entry') || preview.reason?.includes('overrides "mcp.servers.notchlet"'))) return { ...preview, present: true };
  return { ...preview, present: preview.action === 'unchanged' };
}

export type RemoveOptions = { apply?: boolean; allowModified?: boolean };

export async function removeMcpProjectConfig(rootInput: string, client: McpClient, options: RemoveOptions = {}): Promise<{ client: McpClient; path: string; relativePath: string; action: 'not-configured' | 'removed' | 'conflict'; reason?: string }> {
  const root = path.resolve(rootInput);
  const { file, relative, loaded, problem } = await loadConfig(root, client);
  if (!loaded.exists) return { client, path: file, relativePath: relative, action: 'not-configured' };
  if (problem) return { client, path: file, relativePath: relative, action: 'conflict', reason: problem };
  const value = loaded.value!;
  let servers: any;
  if (client === 'claude') servers = value.mcpServers;
  else {
    const mcp = value.mcp;
    if (mcp && typeof mcp === 'object' && !Array.isArray(mcp) && mcp.servers !== undefined) {
      if (!mcp.servers || typeof mcp.servers !== 'object' || Array.isArray(mcp.servers)) return { client, path: file, relativePath: relative, action: 'conflict', reason: 'Configuration key "mcp.servers" must be an object.' };
      // Prefer the V2 entry the setup flow manages; a shadowing flat entry is left untouched.
      servers = mcp.servers.notchlet !== undefined ? mcp.servers : mcp;
    } else servers = mcp;
  }
  if (!servers || typeof servers !== 'object' || Array.isArray(servers) || servers.notchlet === undefined) return { client, path: file, relativePath: relative, action: 'not-configured' };
  if (!options.allowModified) {
    const existing: any = servers.notchlet;
    const looksGenerated = client === 'opencode'
      ? (Array.isArray(existing?.command) && existing.command[0] === 'notchlet' && existing.command[1] === 'mcp' && existing.command[2] === 'serve')
        || (existing?.type === 'remote' && typeof existing.url === 'string' && existing.url.endsWith('/mcp'))
      : (existing?.command === 'notchlet' && Array.isArray(existing?.args) && existing.args[0] === 'mcp' && existing.args[1] === 'serve')
        || (existing?.type === 'http' && typeof existing.url === 'string' && existing.url.endsWith('/mcp'));
    if (!looksGenerated) return { client, path: file, relativePath: relative, action: 'conflict', reason: 'The existing Notchlet entry does not look like the generated bridge entry; confirm removal explicitly.' };
  }
  delete servers.notchlet;
  if (options.apply) {
    const temporary = `${file}.${randomUUID()}.tmp`;
    await writeFile(temporary, `${JSON.stringify(value, null, 2)}\n`, { flag: 'wx', mode: 0o600 });
    try { await rename(temporary, file); }
    catch (error) { await rm(temporary, { force: true }); throw error; }
  }
  return { client, path: file, relativePath: relative, action: 'removed' };
}
