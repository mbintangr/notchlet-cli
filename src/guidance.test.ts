import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(packageRoot, '..');
const skillsRepoRoot = path.resolve(repositoryRoot, 'notchlet-skills');

test('canonical state-aware notchlet-super generates validated OpenCode and Claude Code guidance', async () => {
  execFileSync(process.execPath, [path.join(packageRoot, 'scripts', 'generate-guidance.mjs')], { cwd: repositoryRoot, stdio: 'pipe' });
  const source = await readFile(path.join(skillsRepoRoot, 'skills', 'notchlet-super', 'SKILL.md'), 'utf8');
  const mcpSource = await readFile(path.join(skillsRepoRoot, 'skills', 'notchlet-mcp', 'SKILL.md'), 'utf8');
  const opencode = await readFile(path.join(packageRoot, 'guidance', 'generated', 'opencode', 'notchlet-super', 'SKILL.md'), 'utf8');
  const claude = await readFile(path.join(packageRoot, 'guidance', 'generated', 'claude-code', 'notchlet-super', 'SKILL.md'), 'utf8');
  const opencodeMcp = await readFile(path.join(packageRoot, 'guidance', 'generated', 'opencode', 'notchlet-mcp', 'SKILL.md'), 'utf8');
  const claudeMcp = await readFile(path.join(packageRoot, 'guidance', 'generated', 'claude-code', 'notchlet-mcp', 'SKILL.md'), 'utf8');
  const manifest = JSON.parse(await readFile(path.join(packageRoot, 'guidance', 'generated', 'manifest.json'), 'utf8'));
  const compatibility = JSON.parse(await readFile(path.join(packageRoot, 'guidance', 'generated', 'compatibility.json'), 'utf8'));
  assert.equal(opencode, source);
  assert.equal(claude, source);
  assert.equal(opencodeMcp, mcpSource);
  assert.equal(claudeMcp, mcpSource);
  const hash = createHash('sha256').update(source).digest('hex');
  assert.equal(manifest.sourceSha256, hash);
  assert.equal(manifest.skillsRepo, 'mbintangr/notchlet-skills');
  assert.equal(manifest.targets.length, 24);
  assert.ok(manifest.targets.filter((t: any) => t.skill === 'notchlet-super').every((target: any) => target.sha256 === hash));
  assert.deepEqual(compatibility.aliases['notchlet-backlog-planning'].skills, ['notchlet-plan']);
  assert.deepEqual(compatibility.aliases['notchlet-delivery'].skills, ['notchlet-deliver']);
  assert.deepEqual(compatibility.aliases['notchlet-development'].skills, ['notchlet-super']);
  assert.equal(compatibility.source, 'mbintangr/notchlet-skills');
  assert.match(source, /## Capability mode/);
  assert.match(source, /\*\*Connected\*\*[\s\S]*?\*\*Local\*\*[\s\S]*?\*\*Neither\*\*/);
  for (const phase of ['Phase 1 — Plan & grill', 'Phase 2 — Create backlogs', 'Phase 3 — Implement', 'Phase 4 — Deliver', 'Phase 5 — Done']) assert.ok(source.includes(phase), `${phase} must be present`);
  assert.match(source, /notchlet instructions <change> --action plan\|implement\|verify\|resume\|revise/);
  assert.match(source, /notchlet workspace bind/);
  assert.match(source, /notchlet backlog import/);
  assert.match(source, /notchlet change apply/);
  assert.match(source, /notchlet verify <change> --record/);
  assert.match(source, /notchlet sync status\|push\|pull --change/);
  assert.match(source, /notchlet checkpoint --change/);
  assert.match(source, /sync pending/);
  assert.match(source, /Never push, open or merge a PR, deploy, or set DONE without explicit authorization/);
  assert.doesNotMatch(source, /notchlet-init|curl\s+[^\n]*\/mcp/i);
  assert.match(opencodeMcp, /notchlet init --interactive/);
  assert.match(opencodeMcp, /notchlet mcp status/);
  assert.doesNotMatch(opencodeMcp, /your-mcp-token|curl\s+[^\n]*\/mcp|pg\.mbintangr\.com\/mcp/i);
});
